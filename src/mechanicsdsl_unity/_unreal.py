"""
_unreal.py
----------
Unreal Engine 5 ``UActorComponent`` generator.

Emits three files for a DSL system:

* ``<Cls>Dynamics.h`` - the engine-independent C++17 dynamics (parameters,
  RK4, energy) from :mod:`._cppgen`. It has no Unreal includes, so it is
  compiled and numerically tested outside the engine.
* ``<Cls>Component.h`` / ``<Cls>Component.cpp`` - a Blueprint-spawnable
  ``UActorComponent`` that exposes every parameter and initial condition as an
  editable ``UPROPERTY``, integrates in ``TickComponent`` with sub-stepping,
  and publishes energy drift for in-editor diagnostics.

Drop the three files into ``Source/<YourModule>/`` (Unreal 5.0+ is needed for
``double`` Blueprint properties).
"""

from __future__ import annotations

import os
from typing import TYPE_CHECKING, Dict

from ._cppgen import _pascal, params_struct_name, render_dynamics_header

if TYPE_CHECKING:
    from ._bridge import CompiledSystem


def _fmt(v: float) -> str:
    return repr(float(v))


def render_unreal(system: "CompiledSystem") -> Dict[str, str]:
    """Return ``{filename: source}`` for the Unreal component of ``system``."""
    cls = _pascal(system.name)
    up = system.name.upper()
    struct = params_struct_name(system)
    params = sorted(system.parameters)
    n = system.dof

    param_props = "\n".join(
        f'    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MechanicsDSL|Parameters",\n'
        f'              meta = (ToolTip = "{p} [{system.units.get(p, "")}]"))\n'
        f"    double {p} = {_fmt(system.parameters[p])};"
        for p in params
    )
    ic_props = "\n".join(
        f'    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MechanicsDSL|Initial Conditions")\n'
        f"    double Initial_{s} = {_fmt(v)};"
        for s, v in zip(system.state_names, system.initial_state())
    )
    make_params = "\n".join(f"    P.{p} = {p};" for p in params)
    reset_body = "\n".join(
        f"    State[{i}] = Initial_{s};" for i, s in enumerate(system.state_names)
    )
    energy_call = ("mechanicsdsl::energy(State, MakeParams())"
                   if system.energy is not None else "0.0")

    header = f"""\
// Auto-generated by mechanicsdsl-unity. DO NOT EDIT BY HAND.
// {system.name}: {n}-DOF dynamics from MechanicsDSL as an Unreal ActorComponent.
#pragma once

#include "CoreMinimal.h"
#include "Components/ActorComponent.h"
#include "{cls}Dynamics.h"
#include "{cls}Component.generated.h"

UCLASS(ClassGroup = (MechanicsDSL), meta = (BlueprintSpawnableComponent))
class U{cls}Component : public UActorComponent
{{
    GENERATED_BODY()

public:
    U{cls}Component();

{param_props}

{ic_props}

    /** RK4 sub-steps per tick; raise for stiff or fast systems. */
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MechanicsDSL|Integrator",
              meta = (ClampMin = "1"))
    int32 Substeps = 4;

    /** Fixed integration step [s]; 0 uses the frame DeltaTime. */
    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MechanicsDSL|Integrator",
              meta = (ClampMin = "0.0"))
    double FixedTimestep = 0.0;

    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category = "MechanicsDSL|Integrator")
    bool bPaused = false;

    /** Energy E = sum(qdot dL/dqdot) - L of the current state. */
    UPROPERTY(VisibleAnywhere, BlueprintReadOnly, Category = "MechanicsDSL|Diagnostics")
    double Energy = 0.0;

    /** Relative energy drift since the last reset (integration error monitor). */
    UPROPERTY(VisibleAnywhere, BlueprintReadOnly, Category = "MechanicsDSL|Diagnostics")
    double EnergyDrift = 0.0;

    UFUNCTION(BlueprintCallable, Category = "MechanicsDSL")
    void ResetState();

    /** State vector [{", ".join(system.state_names)}]. */
    UFUNCTION(BlueprintCallable, Category = "MechanicsDSL")
    TArray<double> GetState() const;

    UFUNCTION(BlueprintPure, Category = "MechanicsDSL")
    double GetSimTime() const {{ return SimTime; }}

    virtual void TickComponent(float DeltaTime, ELevelTick TickType,
                               FActorComponentTickFunction* ThisTickFunction) override;

protected:
    virtual void BeginPlay() override;

private:
    mechanicsdsl::{struct} MakeParams() const;

    double State[mechanicsdsl::{up}_STATE_DIM] = {{}};
    double SimTime = 0.0;
    double Energy0 = 0.0;
}};
"""

    source = f"""\
// Auto-generated by mechanicsdsl-unity. DO NOT EDIT BY HAND.
#include "{cls}Component.h"

U{cls}Component::U{cls}Component()
{{
    PrimaryComponentTick.bCanEverTick = true;
}}

void U{cls}Component::BeginPlay()
{{
    Super::BeginPlay();
    ResetState();
}}

mechanicsdsl::{struct} U{cls}Component::MakeParams() const
{{
    mechanicsdsl::{struct} P;
{make_params}
    return P;
}}

void U{cls}Component::ResetState()
{{
{reset_body}
    SimTime = 0.0;
    Energy0 = {energy_call};
    Energy = Energy0;
    EnergyDrift = 0.0;
}}

TArray<double> U{cls}Component::GetState() const
{{
    return TArray<double>(State, mechanicsdsl::{up}_STATE_DIM);
}}

void U{cls}Component::TickComponent(float DeltaTime, ELevelTick TickType,
                                    FActorComponentTickFunction* ThisTickFunction)
{{
    Super::TickComponent(DeltaTime, TickType, ThisTickFunction);
    if (bPaused) {{ return; }}
    const mechanicsdsl::{struct} P = MakeParams();
    const double Dt = FixedTimestep > 0.0 ? FixedTimestep : static_cast<double>(DeltaTime);
    const int32 N = FMath::Max(1, Substeps);
    for (int32 S = 0; S < N; ++S)
    {{
        mechanicsdsl::rk4_step(State, Dt / N, P);
    }}
    SimTime += Dt;
    Energy = {energy_call};
    EnergyDrift = FMath::Abs(Energy - Energy0) / FMath::Max(FMath::Abs(Energy0), 1e-12);
}}
"""
    guard = f"MECHANICSDSL_{up}_DYNAMICS_H"
    return {
        f"{cls}Dynamics.h": render_dynamics_header(system, guard, generator="mechanicsdsl-unity"),
        f"{cls}Component.h": header,
        f"{cls}Component.cpp": source,
    }


def write_unreal(system: "CompiledSystem", out_dir: str) -> Dict[str, str]:
    """Write the Unreal files under ``out_dir``; return ``{name: path}``."""
    os.makedirs(out_dir, exist_ok=True)
    written = {}
    for name, text in render_unreal(system).items():
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written[name] = path
    return written
